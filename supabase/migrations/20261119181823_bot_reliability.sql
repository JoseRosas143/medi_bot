create table if not exists public.treatments (
  id integer generated by default as identity primary key,
  name text not null,
  price numeric not null check (price >= 0),
  is_active boolean not null default true
);
create table if not exists public.faqs (
  id integer generated by default as identity primary key,
  question text not null,
  answer text not null,
  is_active boolean not null default true
);

create table if not exists public.whatsapp_receipts (
  message_id text primary key,
  status text not null default 'processing' check (status in ('processing', 'processed', 'failed')),
  created_at timestamptz not null default now()
);

create table if not exists public.appointment_notices (
  event_id text not null,
  scheduled_start timestamptz not null,
  kind text not null check (kind in ('reminder', 'cancellation')),
  state text not null default 'sending' check (state in ('sending', 'accepted', 'rejected', 'uncertain', 'delivered', 'failed')),
  wa_message_id text unique,
  updated_at timestamptz not null default now(),
  primary key (event_id, scheduled_start, kind)
);

create table if not exists public.pending_appointment_actions (
  id uuid primary key default gen_random_uuid(),
  actor_phone text not null,
  action text not null check (action in ('book', 'cancel_patient', 'cancel_clinic')),
  details jsonb not null,
  expires_at timestamptz not null default (now() + interval '15 minutes'),
  handled_at timestamptz
);

alter table public.patients add column if not exists human_session_id uuid;
alter table public.escalation_mappings add column if not exists human_session_id uuid;
alter table public.patients add column if not exists last_inbound_at timestamptz;

alter table public.treatments enable row level security;
alter table public.faqs enable row level security;
alter table public.whatsapp_receipts enable row level security;
alter table public.appointment_notices enable row level security;
alter table public.pending_appointment_actions enable row level security;
revoke all on public.treatments, public.faqs, public.whatsapp_receipts, public.appointment_notices,
  public.pending_appointment_actions from public, anon, authenticated;
grant select, insert, update, delete on public.treatments, public.faqs, public.whatsapp_receipts, public.appointment_notices,
  public.pending_appointment_actions to service_role;
